/**
 * @file lib/receipt/prompt.ts
 * @description AI に渡す指示文。どの提供元にも同じ文を送る。
 * 利用者の情報（ユーザー ID・メール・名前）は入れない（P9）。画像と、この固定の文だけを送る。
 * 返してほしい形は lib/receipt/schema.ts の ReceiptAiResultSchema と一致させる。
 * 明細の金額ずれ（外税・数量×単価・値引き行の取り違え）を防ぐ書き方は mywork#229（2026-10-21 設計書）。
 * 小計と消費税額（内税・外税とも、税率ごと）を読ませるのは app#42。内税／外税は schema.ts の judgeTax が
 * 小計・税・合計の金額の整合で決めるので、AI の tax_mode は金額で決められないときの控えにしか使わない。
 * 同じ品名が続く行・「＠198 2 396」の数量行・「割引 20% -¥40」の行・「内」印の税込の品・税率ごとの対象額の読み方は
 * mywork#1508（2つ目の同名の行が落ち、対象額を読まないため正しい外税のレシートでも警告が出ていた）。
 */

import { RECEIPT_CATEGORIES } from "./categories";

export const RECEIPT_PROMPT = `この画像はお店のレシートです。次の JSON だけを返してください（説明文は不要）。

{
  "is_receipt": レシートの写真なら true、違えば false,
  "currency": 通貨コード（日本円なら "JPY"）,
  "language": レシートの主な言語（日本語なら "ja"、英語なら "en"）,
  "merchant": 店名（読めなければ null）,
  "purchased_at": 購入日 "YYYY-MM-DD"（和暦は西暦に直す。読めなければ null）,
  "subtotal": 「小計」の行に印字された金額（整数の円。小計の行が無い・読めなければ null）,
  "total": お支払い合計の金額（税込・整数の円。「合計」「お買上計」の行。小計ではない。読めなければ null）,
  "tax_mode": 明細の金額が税込なら "inclusive"、税抜（合計の前に「外税」「消費税」の行で税を足している）なら "exclusive"、分からなければ "unknown",
  "tax_lines": [ { "rate": 税率（8 か 10）, "amount": その税率の消費税額（整数の円）, "base": その税率の「対象額」「対象計」に印字された金額（例「(10%対象 ¥585」→ 585。印字が無ければ null） } ]（外税の税額でも「内消費税」「(内税額)」「うち消費税」の表示でも、印字された消費税額を税率ごとに入れる。8%と10%が別の行なら2つ。税額の印字が無ければ []）,
  "items": [ {
    "name": 品名,
    "quantity": 数量（印字が無ければ null）,
    "unit_price": 単価（「単158」「2コ X 158」のように単価が印字されているときだけ。無ければ null）,
    "amount": その行に印字された金額（整数の円。値引きは負の数）,
    "tax_rate": その行の税率（軽減税率の印「※」「*」「◎」「軽」などが付けば 8、付かなければ 10、分からなければ null。印の意味がレシートの下に「◎は軽減税率8%適用商品」のように書かれていればそれに従う。値引きの行は値引きされた商品と同じ税率）,
    "tax_included": 外税のレシートの中で、品名の前後に「内」「内税」の印があり印字の金額が税込の品なら true、それ以外は false,
    "category": ${RECEIPT_CATEGORIES.map((c) => `"${c}"`).join(" / ")} のどれか
  } ]
}

金額の読み方:
- amount は印字された行の金額をそのまま入れる。税を足したり引いたりしない
- 右端に金額が印字された行は、それぞれ1つの明細にする。同じ品名が続けて出てきても、まとめたり、重複とみなして省いたりしない（同じ商品を別々に買った・片方だけ割引された、ということがある）
- 「2コ X 単158」「158円 x 2」「＠198 2 396」のように数量と単価が別の行・同じ行に出ていたら、quantity=2、unit_price=198、amount=396 と分ける（単価を amount に入れない）。品名の行に金額が無く、すぐ下の行に「＠単価 数量 金額」があるときは、その2行で1つの明細
- 例: 「◎野菜ジュース」「＠198 2 396」「◎野菜ジュース 198」「割引 20% -¥40」と並んでいたら、明細は3行: { 野菜ジュース, quantity 2, unit_price 198, amount 396 }、{ 野菜ジュース, amount 198 }、{ 割引, amount -40 }（3行とも税率 8）
- 値引き・割引・クーポンの行は、直前の商品とは別の行にして amount を負の数にする。「20%」のような割合ではなく、印字された値引きの金額（-¥40 なら -40）を入れる。商品の行の金額は値引き前のまま（二重に引かない）
- 消費税の行（外税8%の税額・外税10%の税額・内消費税額・うち消費税 など）は items に入れず tax_lines に入れる。税率ごとの「対象額」は amount ではなく base に入れる
- 「(含む消費税等 ¥137)」「消費税等合計」のように全税率をまとめた税額の行は、税率ごとの税額の行があればそちらだけを tax_lines に入れる（二重に数えない）
- 小計は subtotal に入れる。合計（total）とは別の行。小計のあとに税や値引きが続くときも、total は最後にお支払いする合計
- 小計・対象額・お預かり・お釣り・ポイントの表示は items に入れない

カテゴリの付け方:
- 飲食店（レストラン・カフェ・ファストフード・居酒屋）のレシートは全部「外食費」
- スーパー・コンビニの食べ物・飲み物（弁当・惣菜・お菓子も）は「食費」
- 洗剤・ティッシュ・文具・化粧品など、食べ物以外の消耗品は「日用品」
- それ以外・判断できないものは「その他」
- 値引きの行は、値引きされた商品と同じカテゴリ

推測で埋めない。読めない項目は null にする。`;
