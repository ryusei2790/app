/**
 * @file lib/receipt/prompt.ts
 * @description AI に渡す指示文。どの提供元にも同じ文を送る。
 * 利用者の情報（ユーザー ID・メール・名前）は入れない（P9）。画像と、この固定の文だけを送る。
 * 返してほしい形は lib/receipt/schema.ts の ReceiptAiResultSchema と一致させる。
 * 明細の金額ずれ（外税・数量×単価・値引き行の取り違え）を防ぐ書き方は mywork#229（2026-10-21 設計書）。
 */

import { RECEIPT_CATEGORIES } from "./categories";

export const RECEIPT_PROMPT = `この画像はお店のレシートです。次の JSON だけを返してください（説明文は不要）。

{
  "is_receipt": レシートの写真なら true、違えば false,
  "currency": 通貨コード（日本円なら "JPY"）,
  "language": レシートの主な言語（日本語なら "ja"、英語なら "en"）,
  "merchant": 店名（読めなければ null）,
  "purchased_at": 購入日 "YYYY-MM-DD"（和暦は西暦に直す。読めなければ null）,
  "total": お支払い合計の金額（税込・整数の円。読めなければ null）,
  "tax_mode": 明細の金額が税込なら "inclusive"、税抜（合計の前に「外税」「消費税」の行で税を足している）なら "exclusive"、分からなければ "unknown",
  "tax_lines": [ { "rate": 税率（8 か 10）, "amount": その税率の消費税額（整数の円） } ]（外税のときだけ。内税・分からないときは []）,
  "items": [ {
    "name": 品名,
    "quantity": 数量（印字が無ければ null）,
    "unit_price": 単価（「単158」「2コ X 158」のように単価が印字されているときだけ。無ければ null）,
    "amount": その行に印字された金額（整数の円。値引きは負の数）,
    "tax_rate": その行の税率（軽減税率の印「※」「*」「軽」などが付けば 8、付かなければ 10、分からなければ null）,
    "category": ${RECEIPT_CATEGORIES.map((c) => `"${c}"`).join(" / ")} のどれか
  } ]
}

金額の読み方:
- amount は印字された行の金額をそのまま入れる。税を足したり引いたりしない
- 「2コ X 単158」「158円 x 2」のように数量と単価が別の行・同じ行に出ていたら、quantity=2、unit_price=158、amount=316 と分ける（単価を amount に入れない）
- 値引き・割引・クーポンの行は、直前の商品とは別の行にして amount を負の数にする。商品の行の金額は値引き前のまま（二重に引かない）
- 外税のレシートでは、消費税の行（外税8%対象の税額・外税10%の税額 など）は items に入れず tax_lines に入れる
- 小計・対象額・お預かり・お釣り・ポイント・内税額の表示は items に入れない

カテゴリの付け方:
- 飲食店（レストラン・カフェ・ファストフード・居酒屋）のレシートは全部「外食費」
- スーパー・コンビニの食べ物・飲み物（弁当・惣菜・お菓子も）は「食費」
- 洗剤・ティッシュ・文具・化粧品など、食べ物以外の消耗品は「日用品」
- それ以外・判断できないものは「その他」
- 値引きの行は、値引きされた商品と同じカテゴリ

推測で埋めない。読めない項目は null にする。`;
